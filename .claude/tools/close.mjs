#!/usr/bin/env node
// close.mjs [--check] — run from the repo root, with a card in progress. Step «close» of the method.
//
// Runs checks 1 to 12 of commands/close.md with the hashes of ambiguities.md, cites the `once` records
// of checks 13 to 17, checks 18 (the saved /code-review was run, once, and is newer than the production code
// that no closed action names), and writes
// what a tool can know: the mechanical part of specs/<card>/closing.md
// (between its begin and end markers) and the line of specs/<card>/sessions.md. What only the main
// thread knows —the heading, the ASM, F1 and the OUT— stays a `<!-- MAIN: … -->` line it replaces.
// A second run regenerates the block and touches nothing outside it; a closing.md without the block
// (written by hand) is left as it is. `--check` prints and writes nothing.
// Each check ends in one of three states: passed · failed · could not run (a check whose input is not
// recorded is never passed). Exits 0 if every check passed (or was skipped by a module that is off),
// 1 otherwise, 2 with no card in progress.
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { IS_CODE, NOT_PRODUCTION, cardFiles, cardStart, copiedFromKit, currentCard, fileMapLines, git, keyOf, namedIn, pathTokens, relativeTo } from './card.mjs';
import { active, readManifest } from './kit.mjs';
import { laneOf } from './lane.mjs';
import { records } from './once.mjs';
import { cardIdOf, kitUpdates, refreezes } from './refreeze.mjs';
import { closedActionLines, lastWriteOf, missing, writeSessionLines } from './required.mjs';

export const BEGIN = '<!-- close.mjs:begin · regenerated by `node .claude/tools/close.mjs`; what is written inside is lost on the next run -->';
export const END = '<!-- close.mjs:end -->';

const textOf = (path) => (existsSync(path) ? readFileSync(path, 'utf8') : '');
const escape = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const TEST_SOURCE = /\.(m?[jt]sx?|cjs|cts|py|go|cs|java|kt|rb|php|feature)$/;
const SKIP_DIRS = new Set(['node_modules', 'test-results', 'playwright-report', '.git']);
const PLAN_FILE = /^[\w@.-]+(?:\/[\w@.-]+)*\.(?:m?[jt]sx?|cjs|cts|py|go|cs|java|kt|rb|php|html?|s?css|vue|svelte|sql|md|json|ya?ml|sh|feature)$/;
const JARGON = /ASVS|WCAG|V[0-9]+\.[0-9]+|\b[A-Z][0-9]{1,2}\b|ASM-|OUT-/;

const scenariosOf = (snapshot) =>
  [...snapshot.matchAll(/^\s*-\s*\[[ xX]\]\s*([A-Z][A-Z0-9]*-\d+-H\d+-\d+)\b/gm)].map((m) => m[1]);

// The scenarios folder: kit.json when the kit was installed, else the `E2E=` line of METHOD.md. It is a hint:
// the card's tests are the versioned files that carry its tag, wherever they are.
const e2eOf = (root) => readManifest(root)?.e2e ?? textOf(join(root, '.claude', 'METHOD.md')).match(/^E2E=(\S+)/m)?.[1] ?? null;

const folderFiles = (root, folder) => {
  const out = [];
  const walk = (dir) => {
    for (const e of readdirSync(join(root, dir), { withFileTypes: true })) {
      if (SKIP_DIRS.has(e.name)) continue;
      const rel = `${dir}/${e.name}`;
      if (e.isDirectory()) walk(rel); else if (TEST_SOURCE.test(e.name)) out.push(rel);
    }
  };
  if (folder && existsSync(join(root, folder))) walk(folder.replace(/\/$/, ''));
  return out;
};

// The versioned test files that carry a tag of the card, at `rev` or in the working tree.
const taggedFiles = (root, id, rev = null) => {
  if (!id) return [];
  const found = git(root, ['grep', '-l', '-I', '-F', '-e', `@${id}-H`, ...(rev ? [rev] : []), '--', ':(exclude)specs', ':(exclude).claude']);
  if (found.status !== 0) return [];
  return found.stdout.split('\n').filter(Boolean).map((l) => (rev ? l.slice(rev.length + 1) : l)).filter((f) => TEST_SOURCE.test(f));
};

// Whether the repo has a type checker to run: a tsconfig or jsconfig, typescript in a package.json, or the
// build of a compiled language, which is its checker.
const TYPE_CONFIG = /(^|\/)(tsconfig[^/]*\.json|jsconfig[^/]*\.json|\.?mypy\.ini|pyrightconfig\.json|go\.mod|pom\.xml|build\.gradle(\.kts)?|[^/]+\.(csproj|fsproj|sln))$/;
const hasTypeChecker = (root) => {
  const files = (git(root, ['ls-files', '--cached', '--others', '--exclude-standard']).stdout ?? '').split('\n').filter(Boolean);
  if (files.some((f) => TYPE_CONFIG.test(f))) return true;
  return files.some((f) => (/(^|\/)package\.json$/.test(f) && /"typescript"\s*:/.test(textOf(join(root, f))))
    || (/(^|\/)(pyproject\.toml|setup\.cfg|requirements[^/]*\.txt)$/.test(f) && /\b(mypy|pyright)\b/.test(textOf(join(root, f)))));
};

// A `suite` record (`verify.mjs` writes one for the plan's suite line) covers the card's tagged tests when it
// runs without a filter and its paths, if it names any, reach them; it is the whole suite when it names no test file.
const FILTERED = /--grep(?:-invert)?\b|--filter\b|--test-name-pattern|--testNamePattern|--testPathPattern|(?:^|\s)-[gkt]\s/;
const TEST_NAME = /(\.(spec|test)\.[^/]+|_test\.\w+|(^|\/)test_[^/]+\.py|\.feature)$/;
const tokensOf = (command) => command.split(/\s+/).map((t) => t.replace(/^['"]|['"]$/g, '').replaceAll('\\', '/').replace(/^\.\//, '')).filter(Boolean);
const namedTests = (command) => tokensOf(command).filter((t) => TEST_NAME.test(t) && !t.includes('*'));
const globRe = (g) => new RegExp(`^${g.split('**').map((p) => p.replace(/[.+?^${}()|[\]\\]/g, '\\$&').replaceAll('*', '[^/]*')).join('.*')}$`);
// A command that names no path runs everything its runner finds; one that names paths reaches a file only through them.
const reaches = (command, files) => {
  const paths = tokensOf(command).filter((t) => !t.startsWith('-') && (t.includes('/') || t.includes('*')));
  return !paths.length || files.some((f) => paths.some((t) => (t.includes('*') ? globRe(t).test(f) : f === t || f.startsWith(`${t.replace(/\/$/, '')}/`))));
};
const suiteLike = (r) => /^suite\b/.test(r.name) && !FILTERED.test(r.command);

// What `once` recorded for each of the checks 13 to 17: the latest record that fits, else the one that covers it.
const SLOTS = ({ id, tagged }) => [
  [13, 'suite', (r) => /^suite\b/.test(r.name)],
  [14, 'type checker', (r) => /^types?\b/.test(r.name) || /\btsc\b|--noEmit|\bmypy\b|\bpyright\b/.test(r.command)],
  [15, 'scenarios of the card', (r) => /^scenarios?\b/.test(r.name) || r.command.includes(`@${id}`),
    (r) => suiteLike(r) && reaches(r.command, tagged)],
  [16, 'whole suite, no captures', (r) => /^(whole|full|all|regression)\b/.test(r.name), (r) => suiteLike(r) && !namedTests(r.command).length],
  [17, 'captures', (r) => /^captur|^screens?\b/.test(r.name) || /captur/i.test(r.command) || /\bapp\.mjs\s+probe\b/.test(r.command)],
];

const NO_RECORD = {
  15: (id) => `no record of the card's scenarios and no \`suite\` record that covers its tagged tests: run \`node .claude/tools/verify.mjs\`, or \`node .claude/tools/once.mjs scenarios -- <runner> --grep "@${id}"\``,
  16: () => 'no record of the whole suite: `node .claude/tools/verify.mjs` records its suite line; or `node .claude/tools/once.mjs full -- <the whole suite command>`',
  17: () => 'no record of the captures: `node .claude/tools/once.mjs captures -- node .claude/tools/app.mjs probe <steps.json>` (`help.mjs app` shows the steps)',
};

// The laps of /code-review that review-cap.mjs counted for the card, in the git folder of its repo.
const reviewLaps = (root, card) => {
  const gitDir = git(root, ['rev-parse', '--absolute-git-dir']).stdout?.trim();
  try { return Number(JSON.parse(readFileSync(join(gitDir, 'sdd-reviews.json'), 'utf8'))[`${card} · code-review`] ?? 0); } catch { return 0; }
};

const sectionOf = (text, name) => (text.split(/^## /m).find((s) => s.startsWith(name)) ?? '').split('\n').slice(1).join('\n');

export const run = (root, { write = true } = {}) => {
  const cardDir = currentCard(root);
  if (!cardDir) return null;
  const id = cardIdOf(cardDir);
  const card = basename(cardDir);
  const rel = (f) => relativeTo(root, join(cardDir, f));
  const snapshot = textOf(join(cardDir, 'card.snapshot.md'));
  const ambiguities = textOf(join(cardDir, 'ambiguities.md'));
  const plan = textOf(join(cardDir, 'plan.md'));
  const actions = textOf(join(cardDir, 'actions.md')).split(/\r?\n/).map((l) => l.trim());
  const checks = [];
  const add = (n, label, state, detail = '') => checks.push({ n, label, state, detail });
  const verdict = (n, label, bad, ok = '') => add(n, label, bad.length ? 'failed' : 'passed', bad.length ? bad.join('; ') : ok);

  const folder = e2eOf(root);
  const taggedNow = taggedFiles(root, id);
  const files = [...new Set([...taggedNow, ...folderFiles(root, folder)])];
  // Neither a tagged file nor a scenarios folder that exists: nothing was looked at, which is not a pass.
  const tests = files.length || (folder && existsSync(join(root, folder))) ? files.map((file) => ({ file, text: textOf(join(root, file)) })) : null;
  const noFolder = `no versioned test file carries @${id}-H and the scenarios folder ${folder ? `${folder} does not exist` : 'is not recorded (E2E= in .claude/METHOD.md)'}: write the tests, or \`node .claude/tools/kit.mjs e2e <path>\``;
  const tagRe = new RegExp(`@${escape(id ?? '')}-H\\d+-\\d+(?!\\d)`, 'g');
  const scenarios = scenariosOf(snapshot);

  // 1. snapshot intact since the commit that froze it
  const frozen = ambiguities.match(new RegExp(`^${escape(id ?? '')}-AMB-00 · .*frozen at (\\S+)`, 'm'))?.[1];
  if (!frozen) add(1, 'snapshot intact', 'could not run', `no ${id}-AMB-00 … frozen at <hash> in ambiguities.md`);
  else {
    const diff = git(root, ['diff', '--name-only', `${frozen}..HEAD`, '--', rel('card.snapshot.md')]);
    if (diff.status !== 0) add(1, 'snapshot intact', 'could not run', `git diff ${frozen}..HEAD failed: ${diff.stderr?.trim()}`);
    else verdict(1, 'snapshot intact', diff.stdout.trim() ? [`${rel('card.snapshot.md')} changed since ${frozen}`] : [], `unchanged since ${frozen}`);
  }

  // 2 and 3. scenarios and tags
  if (!tests) { add(2, 'every scenario has a test', 'could not run', noFolder); add(3, 'every tag is in the snapshot', 'could not run', noFolder); }
  else {
    const tagged = (s) => tests.filter((t) => new RegExp(`@${escape(s)}(?!\\d)`).test(t.text));
    const lacking = scenarios.filter((s) => !tagged(s).length);
    verdict(2, 'every scenario has a test', scenarios.length ? lacking.map((s) => `${s} has none`) : ['the snapshot lists no scenario'], `${scenarios.length} scenarios, each in at least one file`);
    const found = [...new Set(tests.flatMap((t) => t.text.match(tagRe) ?? []))].sort();
    const strangers = found.filter((t) => !scenarios.includes(t.slice(1)));
    verdict(3, 'every tag is in the snapshot', strangers.map((t) => `${t} is not a scenario of the snapshot`), `${found.length} tags`);
  }

  // 4 to 6. assumptions
  const asmLines = plan.split(/\r?\n/).filter((l) => /ASM-\d+ ·/.test(l));
  const asms = [...new Set(asmLines.map((l) => l.match(/([A-Z][A-Z0-9]*-\d+-ASM-\d+) ·/)?.[1]).filter(Boolean))];
  const uncovered = sectionOf(plan, 'Uncovered assumptions');
  let untagged = asms;
  if (!tests) { add(4, 'each ASM is tagged…', 'could not run', noFolder); add(5, '…or declared uncovered', 'could not run', noFolder); }
  else {
    untagged = asms.filter((a) => !tests.some((t) => t.text.includes(`@assumption:${a}`)));
    add(4, 'each ASM is tagged…', 'passed', `tagged ${asms.length - untagged.length} of ${asms.length}${untagged.length ? `; untagged: ${untagged.join(', ')}` : ''}`);
    verdict(5, '…or declared uncovered', untagged.filter((a) => !uncovered.includes(a)).map((a) => `${a} is neither tagged nor under ## Uncovered assumptions`), 'every untagged one is declared');
  }
  verdict(6, 'each ASM says any-answer', asmLines.filter((l) => !l.includes('any-answer: ')).map((l) => l.trim().slice(0, 60)), `${asmLines.length} lines`);

  // 7. the questions carry no jargon or IDs before the arrow
  const questions = ambiguities.split(/\r?\n/).filter((l) => /AMB-\d+ ·/.test(l) && l.includes('?'))
    .map((l) => ({ line: l, text: l.split(' · ').slice(3).join(' · ').split(' → ')[0] })).filter((q) => JARGON.test(q.text));
  verdict(7, 'the questions have no jargon', questions.map((q) => q.line.slice(0, 80)), 'none found');

  // 8. no tagged test of the card touched since the commit that froze them (the latest frozen/refrozen)
  const frozenTests = [...ambiguities.matchAll(/-TESTS · .*(?:frozen|refrozen) at ([0-9a-f]{7,40})\b/g)].at(-1)?.[1];
  if (!frozenTests) add(8, 'no tagged test touched', 'could not run', `no ${id}-TESTS … frozen at <hash> in ambiguities.md`);
  else {
    // The tagged files at the freeze and now: one deleted or moved since is a change too.
    const tagged = [...new Set([...taggedFiles(root, id, frozenTests), ...taggedNow])];
    if (!tagged.length) add(8, 'no tagged test touched', 'could not run', noFolder);
    else {
      const diff = git(root, ['diff', '--name-only', `${frozenTests}..HEAD`, '--', ...tagged.map((f) => `:(literal)${f}`)]);
      if (diff.status !== 0) add(8, 'no tagged test touched', 'could not run', `git diff ${frozenTests}..HEAD failed: ${diff.stderr?.trim()}`);
      else verdict(8, 'no tagged test touched', diff.stdout.split('\n').filter(Boolean).map((f) => `${f} changed since ${frozenTests}`), `none of ${tagged.length} tagged file${tagged.length === 1 ? '' : 's'} since ${frozenTests}`);
    }
  }

  // 9. the diff and the File map, both directions
  const base = cardStart(root, cardDir);
  const map = fileMapLines(cardDir);
  if (!map) add(9, 'diff and File map agree', 'could not run', 'the plan has no ## File map');
  else {
    const diff = cardFiles(root, base);
    const outside = diff.filter((f) => !NOT_PRODUCTION.test(f) && !namedIn(map, f, root).length && !copiedFromKit(root, map, f)).map((f) => `${f} is in the diff, not in the map`);
    // The kit's own files are never in the card's diff: a path under `.claude/`, or the bare name of a tool in `.claude/tools/`.
    const kitFile = (t) => t.startsWith('.claude/') || (!t.includes('/') && existsSync(join(root, '.claude', 'tools', t)));
    const named = [...new Set(map.flatMap(pathTokens).filter((t) => PLAN_FILE.test(t) && !kitFile(t)))];
    const absent = named.filter((t) => !diff.some((f) => f === t || f.endsWith(`/${t}`))).map((t) => `${t} is in the map, not in the diff`);
    verdict(9, 'diff and File map agree', [...outside, ...absent], `${diff.length} files in the diff against ${base}`);
  }

  // 10 and 11. actions
  verdict(10, 'no action open', actions.filter((l) => /· (open|suspect)$/.test(l)).map((l) => l.split(' · ')[0]), 'none open or suspect');
  verdict(11, 'every closed action carries its output', actions.filter((l) => /· closed$/.test(l)).map((l) => l.split(' · ')[0]), 'none without output');

  // The session line before 12: required.mjs asks for it.
  const wrote = [];
  if (write) for (const _ of writeSessionLines(root, cardDir)) wrote.push(rel('sessions.md'));

  // 12. what the diff makes necessary
  try {
    const lacking = missing(root, { closing: false }) ?? [];
    verdict(12, 'required.mjs', lacking, 'everything required ran and passed on this code');
  } catch (e) { add(12, 'required.mjs', 'could not run', e.message); }

  // 13 to 17. the records `once` kept
  const { known, on, off, grade, manifest, exempt } = active(root);
  const recorded = records(root).filter((r) => r.command).sort((a, b) => String(a.when).localeCompare(String(b.when)));
  const typed = hasTypeChecker(root);
  for (const [n, label, fits, covers] of SLOTS({ id, tagged: taggedNow })) {
    if (n === 14 && !typed) { add(n, label, 'could not run', 'no type checker in this repo (no tsconfig or jsconfig, no typescript in package.json): there is nothing to run'); continue; }
    const direct = recorded.filter(fits).at(-1);
    const r = direct ?? (covers ? recorded.filter(covers).at(-1) : undefined);
    if (n === 17 && !r && known.includes('ui') && !on.has('ui')) { add(n, label, 'skipped', 'module ui is off by decision'); continue; }
    if (!r) { add(n, label, 'could not run', NO_RECORD[n]?.(id) ?? 'no record in .validation/once: run it with once.mjs'); continue; }
    const cite = `${r.name} · ${r.command} · exit ${r.exit} · ${r.when}${direct ? '' : ' · the suite covers it'}`;
    if (r.exit !== 0) add(n, label, 'failed', cite);
    else if (r.key !== keyOf(root, r.command)) add(n, label, 'could not run', `${cite} · ran on other code: run it again`);
    else add(n, label, 'passed', `${cite} · on this code`);
  }

  // 18. the /code-review of the card is saved and is newer than the production code it read
  const review = join(cardDir, 'code-review.md');
  const code = cardFiles(root, base).filter((f) => IS_CODE.test(f) && !NOT_PRODUCTION.test(f) && existsSync(join(root, f)));
  if (laneOf(plan) === 'fast') add(18, 'code review saved', 'skipped', 'fast lane');
  else if (exempt.without.has('reviewer')) add(18, 'code review saved', 'skipped', `off by grade: ${grade}`);
  else if (!code.length) add(18, 'code review saved', 'skipped', 'no production code in the diff');
  else if (!existsSync(review)) add(18, 'code review saved', 'failed', `${rel('code-review.md')} does not exist · run /code-review over the card's repo and base (\`node .claude/tools/review-range.mjs ${rel('')}\` prints them) and save its report as ${rel('code-review.md')}`);
  else if (!reviewLaps(root, card)) add(18, 'code review saved', 'failed', `${rel('code-review.md')} exists but no /code-review lap is registered for ${card} in .git/sdd-reviews.json: a report written by hand is not a review · run /code-review once over the card's repo and base (\`node .claude/tools/review-range.mjs ${rel('')}\` prints the args) and save its report as ${rel('code-review.md')}`);
  else {
    const at = lastWriteOf(root, rel('code-review.md'));
    const closed = closedActionLines(cardDir);
    const stale = code.filter((f) => lastWriteOf(root, f) > at && !namedIn(closed, f, root).length);
    verdict(18, 'code review saved', stale.length ? [`${rel('code-review.md')} is older than ${stale.join(', ')}: close the action that changed each file in actions.md (\`ACT-NN · … in <file> · close: <command> · closed · <output>\`); /code-review does not run again`] : [], `${rel('code-review.md')} is newer than the ${code.length} production file${code.length === 1 ? '' : 's'}`);
  }

  const result = { cardDir, checks, wrote, closing: null };
  if (write) result.closing = writeClosing(root, cardDir, { card, id, checks, untagged, asms, ambiguities, base, off, grade, manifest });
  return result;
};

const bullets = (checks, state) => {
  const lines = checks.filter((c) => (state === 'passed' ? ['passed', 'skipped'] : [state]).includes(c.state))
    .map((c) => `- ${c.n} · ${c.label}${c.state === 'skipped' ? ' · skipped' : ''}${c.detail ? ` — ${c.detail}` : ''}`);
  return lines.length ? lines.join('\n') : 'none';
};

const blockOf = (root, { id, checks, ambiguities, base, off, grade, manifest, cardDir }) => {
  const parts = [BEGIN, '## Passed', bullets(checks, 'passed'), '', '## Failed', bullets(checks, 'failed'), '', '## Could not run', bullets(checks, 'could not run')];
  const rfz = refreezes(cardDir);
  if (rfz.length) {
    parts.push('', '## Refrozen tests', ...rfz.map((r) => {
      const stat = git(root, ['diff', '--shortstat', base, '--', r.file]).stdout?.trim() || 'no diff against the card base';
      return `- ${r.file} · ${r.tag} · ${r.reason} · ${r.change} · ${stat}`;
    }));
  }
  const kit = kitUpdates(cardDir);
  if (kit.length) {
    parts.push('', '## Kit updated during the card', ...kit.map((k) => `- ${ambiguities.split(/\r?\n/).find((l) => l.startsWith(`${k} · `))} · needed: <!-- MAIN: what the card needed from the new kit -->`));
  }
  const decisions = [...off].map(([name, o]) => `- module ${name} off by decision: ${o.reason}`);
  if (grade !== 'production') decisions.push(`- grade: ${grade} — ${manifest?.grade?.reason ?? ''}`);
  if (decisions.length) parts.push('', '## Decisions of the repo', ...decisions);
  parts.push(END);
  return parts.join('\n');
};

const writeClosing = (root, cardDir, ctx) => {
  const path = join(cardDir, 'closing.md');
  const block = blockOf(root, { ...ctx, cardDir });
  if (existsSync(path)) {
    const text = readFileSync(path, 'utf8');
    const from = text.indexOf(BEGIN);
    const to = text.indexOf(END);
    if (from < 0 || to < from) return 'kept';
    writeFileSync(path, `${text.slice(0, from)}${block}${text.slice(to + END.length)}`);
    return 'regenerated';
  }
  const { id, untagged, asms, ambiguities } = ctx;
  const outs = [...new Set(ambiguities.match(new RegExp(`${escape(id)}-OUT-\\d+`, 'g')) ?? [])];
  const inspection = existsSync(join(cardDir, 'inspection.md')) ? `inspection.md${existsSync(join(cardDir, 'review.md')) ? ' and review.md' : ''}` : 'inspection.md (not written yet)';
  writeFileSync(path, [
    `# ${ctx.card} — closing`, '',
    '<!-- MAIN: heading · replace this line with passed or not passed: anything under Failed or Could not run is not passed, and which -->', '',
    `<!-- MAIN: ASM · ${asms.length} assumption${asms.length === 1 ? '' : 's'}, untested: ${untagged.join(', ') || 'none'} · replace this line with the ASM count first, the untested ones named, and the unanswered questions and late answers -->`, '',
    `<!-- MAIN: F1 · from ${inspection} · replace this line with the result of F1 and the card link -->`, '',
    `<!-- MAIN: OUT · ${outs.join(', ') || 'none'} · replace this line with each OUT-NN and its severity, and the notices a file asks for -->`, '',
    block, '',
  ].join('\n'));
  return 'written';
};

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const check = process.argv.includes('--check');
  const result = run(process.cwd(), { write: !check });
  if (!result) {
    console.error('No card in progress: nothing to close.');
    process.exit(2);
  }
  for (const c of result.checks) console.log(`${c.n} · ${c.label} · ${c.state}${c.detail ? ` — ${c.detail}` : ''}`);
  for (const f of new Set(result.wrote)) console.log(`${f}: line added`);
  const closing = relativeTo(process.cwd(), join(result.cardDir, 'closing.md'));
  if (result.closing === 'kept') console.log(`${closing} exists and has no close.mjs block: not overwritten; keep its sections in line with the output above.`);
  else if (result.closing) {
    console.log(`${closing} ${result.closing}: the mechanical part is in; replace the <!-- MAIN: … --> lines (heading, ASM, F1, OUT), printed here so closing.md is not read again:`);
    for (const l of textOf(join(result.cardDir, 'closing.md')).split(/\r?\n/)) if (l.startsWith('<!-- MAIN: ')) console.log(l);
  }
  const bad = result.checks.filter((c) => !['passed', 'skipped'].includes(c.state));
  console.log(bad.length ? `Not passed: ${bad.map((c) => `${c.n} ${c.state}`).join(', ')}.` : 'All 18 checks passed.');
  process.exit(bad.length ? 1 : 0);
}
